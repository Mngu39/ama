"""Analyze real per-game evaluation files for the Short/Long Horizon (hypothesis 2).

Usage: python analysis/horizon2_compare.py --a /path/A/episodes.csv --b /path/B/episodes.csv --c /path/C/episodes.csv --out /path/results
No evaluation results are generated by this script. It rejects nonmatching eval seeds.
"""
import argparse
import json
from pathlib import Path
import sys

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

REQUIRED=('seed','total_score','max_chain','turns','simulated_candidates',
          'evaluated_candidates','decision_time_seconds')
NAMES={'A':'Short 3-ply (A)','B':'Long uniform (B)','C':'Long predictor (C)'}


def read_episodes(file):
    file=Path(file)
    if file.is_dir():
        file=file/'episodes.csv'
    if not file.is_file():
        raise FileNotFoundError(f'평가 파일 없음: {file}')
    df=pd.read_csv(file)
    missing=[col for col in REQUIRED if col not in df]
    if missing:
        raise ValueError(f'{file.name} 필수 컬럼 없음: {missing}')
    if df.empty:
        raise ValueError(f'{file} 비어 있음; 실제 평가 로그가 필요합니다')
    if df['seed'].duplicated().any():
        raise ValueError(f'{file} 평가 seed 중복')
    for col in REQUIRED:
        df[col]=pd.to_numeric(df[col],errors='raise')
    if df[list(REQUIRED)].isna().any().any():
        raise ValueError(f'{file} 필수 컬럼 결측')
    if (df[['turns','simulated_candidates','evaluated_candidates','decision_time_seconds']]<0).any().any():
        raise ValueError(f'{file} 음수 계산량 또는 시간')
    return df.sort_values('seed').reset_index(drop=True)


def compare(a=None,b=None,c=None, out=None, expected_games=250):
    provided={k:v for k,v in (('A',a),('B',b),('C',c)) if v is not None}
    if 'A' not in provided:
        raise ValueError('Baseline 평가 A(--a)가 있어야 합니다')
    frames={k:read_episodes(f) for k,f in provided.items()}
    seeds=frames['A']['seed'].tolist()
    for k,df in frames.items():
        if df['seed'].tolist()!=seeds:
            raise ValueError(f'{k} 평가 seed가 A와 다릅니다: 동일 게임에서 비교해야 합니다')
    out=Path(out or 'horizon2_analysis')
    out.mkdir(parents=True,exist_ok=True)
    rows=[]
    for k,df in frames.items():
        rows.append({
            'group':k, 'name':NAMES[k], 'games':int(len(df)),
            'seed_min':int(df.seed.min()),'seed_max':int(df.seed.max()),
            'mean_score':float(df.total_score.mean()),
            'mean_max_chain':float(df.max_chain.mean()),
            'rate_chain_ge5':float((df.max_chain>=5).mean()),
            'rate_chain_ge7':float((df.max_chain>=7).mean()),
            'mean_seconds_per_game':float(df.decision_time_seconds.mean()),
            'mean_seconds_per_decision':float((df.decision_time_seconds.sum()/df.turns.sum()) if df.turns.sum()>0 else np.nan),
            'mean_simulated_candidates_per_turn':float((df.simulated_candidates.sum()/df.turns.sum()) if df.turns.sum()>0 else np.nan),
            'mean_evaluated_candidates_per_turn':float((df.evaluated_candidates.sum()/df.turns.sum()) if df.turns.sum()>0 else np.nan),
        })
    result=pd.DataFrame(rows)
    result.to_csv(out/'horizon2_group_summary.csv',index=False,encoding='utf-8-sig')
    pairs=[('B','A'),('C','B'),('C','A')]
    pairrows=[]
    for v,w in pairs:
        if v not in frames or w not in frames:continue
        d=frames[v].set_index('seed')[['total_score','max_chain','decision_time_seconds']]-frames[w].set_index('seed')[['total_score','max_chain','decision_time_seconds']]
        pairrows.append({'comparison':f'{v}-{w}','games':len(d),
                         'mean_score_delta':float(d.total_score.mean()),
                         'mean_max_chain_delta':float(d.max_chain.mean()),
                         'mean_decision_time_delta_sec_per_game':float(d.decision_time_seconds.mean())})
    pd.DataFrame(pairrows,columns=['comparison','games','mean_score_delta','mean_max_chain_delta','mean_decision_time_delta_sec_per_game']).to_csv(
        out/'horizon2_paired_differences.csv',index=False,encoding='utf-8-sig')
    for metric,ylabel,name in [('mean_max_chain','Mean maximum chain','mean_max_chain'),
                               ('mean_score','Mean score','mean_score'),
                               ('mean_seconds_per_game','Decision time (s) / game','decision_time')]:
        fig,ax=plt.subplots(figsize=(7,4))
        ax.bar(result.group,result[metric])
        ax.set(xlabel='Group',ylabel=ylabel,title=f'Horizon2: {ylabel}')
        ax.grid(axis='y',alpha=0.2)
        fig.tight_layout();fig.savefig(out/f'{name}.png',dpi=160);plt.close(fig)
    warnings=[]
    if len(seeds)!=expected_games: warnings.append(f'게임 {len(seeds)}판: 계획 {expected_games}판과 다름')
    if sorted(frames)!=['A','B','C']:warnings.append('A/B/C 일부 실험군만 있음: 가설2 전체 검증 결과는 아직 아님')
    if not set(seeds).isdisjoint(range(12345,32345)):
        warnings.append('학습 seed 범위 12345~32344와 평가 seed 중복 가능성 확인 필요')
    warnings += [
        'B/C의 미래 뿌요 정보 누출 여부, 학습한 GTR 가중치 동일 여부, 5-ply 탐색 조건 및 연산 예산 동일 여부는 이 CSV만으로 검증 불가능.',
        '이 결과는 평가 게임 집계이며 예측 정확도 측정은 별도 정답 레이블/예측 CSV가 필요.',
        '같은 평가 seed에서 페어링한 평균 차이는 설명적 비교이며, 학습 seed 반복이 없으면 통계적 일반화는 제한됨.',
        'A→B 변화에는 탐색 깊이/연산량도 포함됨. C−B를 예측 분포의 추가 효과 비교로 해석하려면 B/C 모든 조건이 동일해야 함.',
    ]
    (out/'검증_주의사항.txt').write_text('\n'.join('- '+w for w in warnings)+'\n',encoding='utf8')
    print(result.to_string(index=False))
    print('실제 평가 결과를 분석해 저장:',out,' / 경고: ',len(warnings),'개')
    return result

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--a',required=True,type=Path)
    p.add_argument('--b',type=Path);p.add_argument('--c',type=Path)
    p.add_argument('--out',type=Path,required=True);p.add_argument('--expected-games',type=int,default=250)
    z=p.parse_args()
    try:
        compare(a=z.a,b=z.b,c=z.c,out=z.out,expected_games=z.expected_games)
    except (ValueError,FileNotFoundError) as e:
        p.error(str(e))
